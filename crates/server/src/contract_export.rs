use serde_json::Value;
fn ts(schema: &Value) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        return reference.rsplit('/').next().unwrap_or("unknown").into();
    }
    if let Some(values) = schema["enum"].as_array() {
        return values
            .iter()
            .map(|v| v.to_string())
            .collect::<Vec<_>>()
            .join(" | ");
    }
    for (key, separator) in [("oneOf", " | "), ("anyOf", " | "), ("allOf", " & ")] {
        if let Some(values) = schema[key].as_array() {
            return values.iter().map(ts).collect::<Vec<_>>().join(separator);
        }
    }
    if let Some(types) = schema["type"].as_array() {
        return types
            .iter()
            .map(|kind| {
                let mut narrowed = schema.clone();
                narrowed["type"] = kind.clone();
                ts(&narrowed)
            })
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match schema["type"].as_str() {
        Some("string") => if schema["format"] == "binary" {
            "Blob"
        } else {
            "string"
        }
        .into(),
        Some("integer" | "number") => "number".into(),
        Some("boolean") => "boolean".into(),
        Some("null") => "null".into(),
        Some("array") => format!("Array<{}>", ts(&schema["items"])),
        Some("object") | None
            if schema.get("properties").is_some()
                || schema.get("additionalProperties").is_some() =>
        {
            let required = schema["required"].as_array().cloned().unwrap_or_default();
            let fields = schema["properties"]
                .as_object()
                .map(|properties| {
                    properties
                        .iter()
                        .map(|(name, value)| {
                            format!(
                                "{}{}: {};",
                                serde_json::to_string(name).unwrap(),
                                if required.iter().any(|v| v == name) {
                                    ""
                                } else {
                                    "?"
                                },
                                ts(value)
                            )
                        })
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default();
            if fields.is_empty() {
                let value = match &schema["additionalProperties"] {
                    Value::Object(_) => ts(&schema["additionalProperties"]),
                    _ => "unknown".into(),
                };
                format!("Record<string, {value}>")
            } else {
                format!("{{ {} }}", fields.join(" "))
            }
        }
        Some("object") => "Record<string, unknown>".into(),
        _ => "unknown".into(),
    }
}
pub fn typescript(document: &Value) -> String {
    let mut output="// Generated by cargo run -q -p beweft-server --bin beweft-contract -- --typescript. Do not edit.\n\n".to_string();
    if let Some(schemas) = document["components"]["schemas"].as_object() {
        for (name, schema) in schemas {
            output.push_str(&format!("export type {name} = {};\n", ts(schema)));
        }
    }
    output.push_str("\nexport interface ApiOperations {\n");
    if let Some(paths) = document["paths"].as_object() {
        for (path, operations) in paths {
            for (method, operation) in operations.as_object().unwrap() {
                let body = &operation["requestBody"]["content"];
                let request = if body.get("multipart/form-data").is_some() {
                    "FormData".into()
                } else if let Some(content) = body.get("application/json") {
                    ts(&content["schema"])
                } else {
                    "undefined".into()
                };
                let responses = &operation["responses"]["200"]["content"];
                let response = if let Some(content) = responses.get("application/json") {
                    ts(&content["schema"])
                } else if responses.is_null() {
                    "undefined".into()
                } else {
                    "Blob".into()
                };
                let query = operation["parameters"]
                    .as_array()
                    .map(|params| {
                        params
                            .iter()
                            .filter(|p| p["in"] == "query")
                            .map(|p| {
                                format!(
                                    "{}{}: {};",
                                    p["name"],
                                    if p["required"] == true { "" } else { "?" },
                                    ts(&p["schema"])
                                )
                            })
                            .collect::<Vec<_>>()
                    })
                    .unwrap_or_default()
                    .join(" ");
                output.push_str(&format!(
                    "  {}: {{ request: {request}; response: {response}; query: {{ {query} }} }};\n",
                    serde_json::to_string(&format!("{} {path}", method.to_uppercase())).unwrap()
                ));
            }
        }
    }
    output.push_str("}\n");
    output
}
